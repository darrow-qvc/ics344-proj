#!/usr/bin/env python3
"""
pty_tests.py - interactive job-control tests for MiniSh.

These drive the shell through a pseudo-terminal so that Ctrl+C / Ctrl+Z
are generated by the tty driver exactly as on a real console, and so the
terminal-ownership handoff (tcsetpgrp) can be observed from outside.

    python3 tests/pty_tests.py build/minish          run everything
    python3 tests/pty_tests.py build/minish -v       show the transcript

Each test prints PASS/FAIL; the exit status is non-zero if any failed.
"""
import os, pty, re, select, signal, sys, time

SHELL = os.path.abspath(sys.argv[1])
if not os.access(SHELL, os.X_OK):
    sys.exit("pty_tests.py: %s is not an executable; run make first" % SHELL)
VERBOSE = "-v" in sys.argv
CTRL_C, CTRL_Z, CTRL_D = "\x03", "\x1a", "\x04"


class Shell:
    def __init__(self):
        self.pid, self.fd = pty.fork()
        if self.pid == 0:
            os.environ["HOME"] = "/"
            os.execv(SHELL, [SHELL])
        self.log = ""
        self.expect("minish> ")

    def send(self, s):
        os.write(self.fd, s.encode())

    def read(self, timeout=0.5):
        out = b""
        end = time.time() + timeout
        while time.time() < end:
            r, _, _ = select.select([self.fd], [], [], 0.05)
            if r:
                try:
                    chunk = os.read(self.fd, 4096)
                except OSError:
                    break
                if not chunk:
                    break
                out += chunk
        text = out.decode(errors="replace").replace("\r\n", "\n")
        self.log += text
        if VERBOSE:
            sys.stdout.write(text)
        return text

    def expect(self, needle, timeout=3.0):
        """Read until needle appears; return everything read."""
        got = ""
        end = time.time() + timeout
        while time.time() < end:
            got += self.read(0.1)
            if needle in got:
                return got
        raise AssertionError("timeout waiting for %r, got %r" % (needle, got))

    def cmd(self, line, timeout=3.0):
        """Send a line and return the output up to the next prompt."""
        self.send(line + "\n")
        out = self.expect("minish> ", timeout)
        return out

    def children(self):
        """pids of live children of the shell (via /proc)."""
        kids = []
        for d in os.listdir("/proc"):
            if not d.isdigit():
                continue
            try:
                with open("/proc/%s/stat" % d) as f:
                    fields = f.read().split()
                if int(fields[3]) == self.pid:
                    kids.append((int(d), fields[2]))
            except OSError:
                pass
        return kids

    def fd_count(self):
        return len(os.listdir("/proc/%d/fd" % self.pid))

    def close(self):
        try:
            os.kill(self.pid, signal.SIGKILL)
        except OSError:
            pass
        try:
            os.waitpid(self.pid, 0)
        except OSError:
            pass
        os.close(self.fd)


def proc_state(pid):
    with open("/proc/%d/stat" % pid) as f:
        return f.read().split()[2]


tests = []
def test(fn):
    tests.append(fn); return fn


@test
def ctrl_z_stops_only_foreground_job(sh):
    sh.send("sleep 30\n"); time.sleep(0.3)
    sh.send(CTRL_Z)
    out = sh.expect("minish> ")
    assert "[1]+  Stopped" in out and "sleep 30" in out, out
    (pid, state), = sh.children()
    assert state == "T", "sleep should be stopped, state=%s" % state
    # the shell took the terminal back
    assert os.tcgetpgrp(sh.fd) == sh.pid, "shell does not own the terminal"
    out = sh.cmd("jobs")
    assert "[1]+  Stopped                 sleep 30" in out, out


@test
def bg_resumes_stopped_job(sh):
    sh.send("sleep 30\n"); time.sleep(0.3); sh.send(CTRL_Z); sh.expect("minish> ")
    (pid, _), = sh.children()
    out = sh.cmd("bg")
    assert "[1]+ sleep 30 &" in out, out
    time.sleep(0.1)
    assert proc_state(pid) == "S", "sleep should be running again"
    out = sh.cmd("jobs")
    assert "Running                 sleep 30 &" in out, out


@test
def fg_then_ctrl_c_kills_only_the_job(sh):
    sh.cmd("sleep 30 &")
    sh.send("fg\n"); time.sleep(0.3)
    assert os.tcgetpgrp(sh.fd) != sh.pid, "job should own the terminal during fg"
    sh.send(CTRL_C)
    out = sh.expect("minish> ")
    assert sh.children() == [], "sleep should be gone: %r" % sh.children()
    assert os.tcgetpgrp(sh.fd) == sh.pid
    out = sh.cmd("jobs")
    assert "sleep" not in out, out
    assert sh.cmd("echo alive").count("alive") >= 1   # shell survived Ctrl+C


@test
def ctrl_c_at_prompt_does_not_kill_shell(sh):
    sh.send(CTRL_C); time.sleep(0.2)
    out = sh.cmd("echo alive")
    assert "alive" in out, out


@test
def background_done_notification(sh):
    out = sh.cmd("sleep 0.3 &")
    assert re.search(r"\[1\] \d+", out), out
    time.sleep(0.5)
    out = sh.cmd("")           # empty line: notifications are printed before the prompt
    assert "[1]+  Done                    sleep 0.3" in out, out
    assert sh.children() == []


@test
def stopped_pipeline_resumes_with_terminal(sh):
    sh.send("cat | tr a-z A-Z\n"); time.sleep(0.2)
    sh.send(CTRL_Z)
    out = sh.expect("minish> ")
    assert "Stopped" in out and "cat | tr a-z A-Z" in out, out
    assert sorted(st for _, st in sh.children()) == ["T", "T"], sh.children()
    sh.send("fg\n"); time.sleep(0.2)
    sh.send("hello\n"); time.sleep(0.2)
    sh.send(CTRL_D)
    out = sh.expect("minish> ")
    assert "HELLO" in out, out
    assert sh.children() == []


@test
def external_sigstop_on_background_job(sh):
    out = sh.cmd("sleep 30 &")
    pid = int(re.search(r"\[1\] (\d+)", out).group(1))
    os.kill(pid, signal.SIGSTOP); time.sleep(0.2)
    out = sh.cmd("jobs")
    assert "Stopped                 sleep 30" in out, out
    out = sh.cmd("bg %1")
    assert "sleep 30 &" in out, out
    time.sleep(0.1)
    assert proc_state(pid) == "S"
    out = sh.cmd("jobs")
    assert "Running" in out, out
    os.kill(pid, signal.SIGTERM); time.sleep(0.2)
    out = sh.cmd("")
    assert "Terminated" in out and "sleep 30" in out, out


@test
def quick_exiting_children_leave_no_zombies(sh):
    for _ in range(30):
        sh.cmd("true &")
    for _ in range(20):
        sh.cmd("true | true | true")
    time.sleep(0.3)
    sh.cmd("")
    zombies = [p for p, st in sh.children() if st == "Z"]
    assert not zombies, "zombies: %r" % zombies
    assert sh.children() == [], sh.children()
    out = sh.cmd("jobs")
    assert "true" not in out, out


@test
def shell_leaks_no_descriptors(sh):
    before = sh.fd_count()
    for _ in range(20):
        sh.cmd("echo x | cat | cat | cat > /dev/null")
        sh.cmd("cat < /etc/hostname > /dev/null")
    sh.cmd("echo a | nosuchcommand | cat")
    sh.cmd("cat < /no/such/file | cat")
    after = sh.fd_count()
    assert before == after, "fd count %d -> %d" % (before, after)


@test
def job_numbering_and_fg_by_id(sh):
    sh.cmd("sleep 30 &"); sh.cmd("sleep 31 &")
    out = sh.cmd("jobs")
    assert "[1]-  Running                 sleep 30 &" in out, out
    assert "[2]+  Running                 sleep 31 &" in out, out
    sh.send("fg %1\n"); out = sh.expect("sleep 30\n"); time.sleep(0.2)
    sh.send(CTRL_C); sh.expect("minish> ")
    out = sh.cmd("jobs")
    assert "sleep 30" not in out and "sleep 31" in out, out
    sh.send("fg\n"); time.sleep(0.2); sh.send(CTRL_C); sh.expect("minish> ")
    assert sh.children() == []
    out = sh.cmd("fg")
    assert "fg: current: no such job" in out, out
    out = sh.cmd("fg %7")
    assert "fg: %7: no such job" in out, out


@test
def exit_warns_about_stopped_jobs(sh):
    sh.send("sleep 30\n"); time.sleep(0.2); sh.send(CTRL_Z); sh.expect("minish> ")
    out = sh.cmd("exit")
    assert "There are stopped jobs." in out, out
    sh.send("exit\n"); time.sleep(0.3)
    _, status = os.waitpid(sh.pid, os.WNOHANG)
    assert status != 0 or _ == sh.pid, "shell should have exited"
    sh.pid_reaped = True


@test
def nonexistent_command_in_foreground_restores_terminal(sh):
    out = sh.cmd("nosuchcommand")
    assert "command not found" in out, out
    assert os.tcgetpgrp(sh.fd) == sh.pid
    out = sh.cmd("nosuchcommand | cat")
    assert "command not found" in out, out
    assert sh.children() == []


def main():
    failed = 0
    for fn in tests:
        sh = Shell()
        try:
            fn(sh)
            print("PASS", fn.__name__)
        except Exception as e:  # noqa
            failed += 1
            print("FAIL", fn.__name__, "-", e)
            if not VERBOSE:
                print("  transcript:", repr(sh.log[-400:]))
        finally:
            # kill leftovers (sleep etc.) then the shell
            for pid, _ in sh.children():
                try: os.kill(pid, signal.SIGKILL)
                except OSError: pass
            if not getattr(sh, "pid_reaped", False):
                sh.close()
    print("----\n%d tests, %d failed" % (len(tests), failed))
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
